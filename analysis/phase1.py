"""Phase 1 analysis over the curated Parquet. Writes docs/phase1/report.md and figures.

Usage: python analysis/phase1.py <curated dir>   (e.g. a local `aws s3 sync` of s3://<bucket>/curated/)
"""

import pathlib
import sys

import duckdb
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "src"))
from river_forecast.features import rain_qc

CUR = pathlib.Path(sys.argv[1]).as_posix()
OUT = pathlib.Path(__file__).resolve().parents[1] / "docs" / "phase1"
OUT.mkdir(parents=True, exist_ok=True)
HD = f"{CUR}/opw_hydrodata/snapshot=*"
RT = f"{CUR}/opw_realtime"
SPIKE_MM_15MIN = 50.0  # no credible Irish 15-min total gets near this
CLONMEL_AREA_KM2 = 2143.97  # Hydro-Data layer metadata

db = duckdb.connect()
db.sql("SET TimeZone='UTC'")
lines = []


def md(s=""):
    lines.append(s)


def q(sql):
    return db.sql(sql).df()


def table(df):
    md("| " + " | ".join(df.columns) + " |")
    md("|" + "---|" * len(df.columns))
    for row in df.itertuples(index=False):
        md("| " + " | ".join(str(v) for v in row) + " |")
    md()


# --- 1. Coverage -----------------------------------------------------------
md("# Phase 1 data analysis")
md()
md("Generated by `analysis/phase1.py` from the curated Parquet (Hydro-Data snapshot 2026-10-24 plus the real-time")
md("archive). All times are UTC. Water levels from Hydro-Data (`S`) are metres OD and equal the real-time `OD` sensor.")
md()
md("## 1. Coverage")
md()
cov = q(f"""
    select param, station_no,
           min(timestamp)::date as first, max(timestamp)::date as last,
           count(*) as rows,
           round(100 * avg((quality_status = 'checked')::int), 1) as pct_checked,
           round(100 * avg((quality_status = 'provisional')::int), 1) as pct_provisional,
           round(100 * avg((quality_status = 'missing')::int), 1) as pct_missing
    from read_parquet('{HD}/param=*/*.parquet')
    where param in ('S', 'Q')
    group by all order by param desc, station_no""")
names = q(f"select distinct station_no, station_name from read_parquet('{HD}/stations/param=*.parquet')")
cov = cov.merge(names, on="station_no", how="left")
cov["first"] = cov["first"].astype(str).str[:10]
cov["last"] = cov["last"].astype(str).str[:10]
cov["catchment"] = np.where(cov.station_no.str.startswith("09"), "Dodder", "Suir")
summary = (
    cov.groupby(["catchment", "param"])
    .agg(stations=("station_no", "count"), earliest=("first", "min"), total_rows=("rows", "sum"))
    .reset_index()
)
table(summary)
md("Real-time only (not on Hydro-Data): Waldron's Bridge 09010, the six FFWS back-up loggers and Hollyford 16201.")
md()
key = cov[cov.station_no.isin(["09369", "16011", "16009", "16002"])][
    ["station_no", "station_name", "param", "first", "last", "pct_checked", "pct_provisional", "pct_missing"]
]
table(key)

# --- 2. Waldron's -> Anglesea lag -------------------------------------------
md("## 2. Waldron's Bridge (09010) to Anglesea Road (09369) lag")
md()
rt = q(f"""select station_no, timestamp, value from read_parquet('{RT}/sensor=0001/*.parquet')
           where station_no in ('09010', '09369')""")
w = rt.pivot_table(index="timestamp", columns="station_no", values="value").asfreq("15min")
x, y = w["09010"], w["09369"]
md(f"Data: real-time 15-min `0001` levels, {w.index.min():%Y-%m-%d %H:%M} to {w.index.max():%Y-%m-%d %H:%M}")
md(f"({len(w)} steps, {int(x.isna().sum())} / {int(y.isna().sum())} missing). Waldron's Bridge has no history on")
md("Hydro-Data, so only the real-time archive (which began with the 2026-09-19 snapshot) can be used.")
md()
xc = [(lag * 15, x.diff().corr(y.diff().shift(-lag))) for lag in range(0, 13)]
best = max(xc, key=lambda t: t[1])
md(f"**Cross-correlation of 15-min changes** peaks at **{best[0]} min** (r = {best[1]:.2f}); r > 0.6 for 15-60 min.")
md()
events = []
for i in range(48, len(x) - 16):
    win = x.iloc[i - 8 : i + 9]
    rise = x.iloc[i] - x.iloc[i - 48 : i].min()
    if x.iloc[i] == win.max() and rise >= 0.08 and (not events or (x.index[i] - events[-1][0]) > pd.Timedelta("12h")):
        j = y.iloc[i : i + 17].idxmax()
        events.append((x.index[i], x.iloc[i], rise, j, y[j], int((j - x.index[i]).total_seconds() / 60)))
ev = pd.DataFrame(events, columns=["waldrons_peak", "waldrons_m", "rise_m", "anglesea_peak", "anglesea_m", "lag_min"])
md(f"**Event peak-to-peak** ({len(ev)} events with a rise of at least 0.08 m at Waldron's Bridge):")
md()
table(ev)
md(f"Median peak lag: **{ev.lag_min.median():.0f} min** (range {ev.lag_min.min()}-{ev.lag_min.max()} min, at 15-min")
md("resolution). So the upstream gauge gives at most about 30-60 minutes of warning for Anglesea Road. Any")
md("useful lead time on the Dodder has to come from rainfall forecasts, not from routing the upstream gauge.")
md("This is only 5 weeks of autumn data. Re-run it as the real-time archive grows.")
md()
fig, ax = plt.subplots(figsize=(10, 3.5))
ax.plot(x.index, x, label="Waldron's Bridge 09010", lw=0.8)
ax.plot(y.index, y, label="Anglesea Road 09369", lw=0.8)
ax.set_ylabel("level (m, local gauge)")
ax.legend(loc="upper left")
ax.set_title("Dodder real-time levels")
fig.tight_layout()
fig.savefig(OUT / "dodder_lag.png", dpi=110)
md("![Dodder levels](dodder_lag.png)")
md()

# --- 3. 14 Nov 2025 at Anglesea Road ---------------------------------------
md("## 3. The 14 November 2025 event in the Anglesea Road record")
md()
nov = q(f"""select timestamp, value, quality_code, quality_status
            from read_parquet('{HD}/param=S/station=09369.parquet')
            where timestamp >= '2025-11-13' and timestamp < '2025-11-17' order by timestamp""")
pk = nov.loc[nov.value.idxmax()]
d14 = nov[(nov.timestamp >= "2025-11-14") & (nov.timestamp < "2025-11-15")]
steps = nov.timestamp.diff().dropna()
md(
    f"- Rows 2025-11-13 to 2025-11-16: **{len(nov)}** (expected 384 at 15 min), gaps > 15 min: {int((steps > pd.Timedelta('15min')).sum())},"
)
md(
    f"  missing values: {int(nov.value.isna().sum())}. Quality codes: {nov.quality_code.value_counts().to_dict()} (31 = checked)."
)
md(
    f"- On 14 Nov the level rose from {d14.value.iloc[0]:.3f} to {d14.value.iloc[-1]:.3f} m OD (day max {d14.value.max():.3f})."
)
md(f"- The peak came after midnight: **{pk.value:.3f} m OD at {pk.timestamp:%Y-%m-%d %H:%M} UTC**.")
peaks = q(f"""with d as (select date_trunc('day', timestamp) d, max(value) v
                         from read_parquet('{HD}/param=S/station=09369.parquet') group by 1)
              select d, v from d order by v desc nulls last""")
# decluster: keep daily maxima separated by >= 3 days
kept = []
for row in peaks.itertuples(index=False):
    if all(abs((row.d - k.d).days) >= 3 for k in kept):
        kept.append(row)
    if len(kept) == 5:
        break
rank = next(
    i
    for i, k in enumerate(kept, 1)
    if k.d.date() in (pd.Timestamp("2025-11-14").date(), pd.Timestamp("2025-11-15").date())
)
md(f"- It is the **#{rank} independent peak** in the Anglesea record (2021-10-06 onwards). Top 5:")
md()
table(pd.DataFrame([(k.d.date(), round(k.v, 3)) for k in kept], columns=["day", "max_m_OD"]))
fig, ax = plt.subplots(figsize=(10, 3.2))
ax.plot(nov.timestamp, nov.value, lw=1)
ax.axvspan(pd.Timestamp("2025-11-14", tz="UTC"), pd.Timestamp("2025-11-15", tz="UTC"), alpha=0.15)
ax.set_ylabel("m OD")
ax.set_title("Anglesea Road 09369, 13-16 Nov 2025 (shaded: 14 Nov)")
fig.tight_layout()
fig.savefig(OUT / "anglesea_2025_11.png", dpi=110)
md("![Anglesea Nov 2025](anglesea_2025_11.png)")
md()

# --- 4. Suir rainfall: OPW gauges ------------------------------------------
md("## 4. Rainfall source assessment for the Suir (OPW rain gauges)")
md()
gauges = q(f"select station_no, station_name, lat, lon from read_parquet('{HD}/stations/param=Precip.parquet')")
daily = q(f"""select station_no, date_trunc('day', timestamp) d,
                     sum(case when value > {SPIKE_MM_15MIN} then null else value end) mm,
                     count(value) n, max(value) mx
              from read_parquet('{HD}/param=Precip/*.parquet') where timestamp < '2026-10-24' group by all""")
qc = q(f"""select station_no, min(timestamp)::date first,
                  round(100 * avg((quality_status = 'provisional')::int), 1) pct_provisional,
                  sum((value > {SPIKE_MM_15MIN})::int) spikes_gt_50mm
           from read_parquet('{HD}/param=Precip/*.parquet') group by 1""")
D = daily[daily.n >= 90].pivot(index="d", columns="station_no", values="mm")
coords = {r.station_no: (r.lat, r.lon) for r in gauges.itertuples()}
flags = rain_qc.flag_gauge_years(D, coords)
D_raw = D.copy()
D = rain_qc.apply_flags(D, flags)
nbs = rain_qc.neighbours({k: v for k, v in coords.items() if k in D.columns})
stats = []
for s in D:
    ref = D[nbs[s]].median(axis=1)
    g = pd.DataFrame({"x": D[s], "o": ref}).dropna()
    raw = pd.DataFrame({"x": D_raw[s], "o": ref}).dropna()
    f = flags[flags.station_no == s]
    stats.append(
        {
            "station_no": s,
            "days_complete": len(raw),
            "r_vs_neighbours": round(g.x.corr(g.o), 2),
            "ratio_vs_neighbours": round(g.x.sum() / g.o.sum(), 2),
            "flagged_years": "; ".join(f"{r}: {','.join(map(str, sorted(v.year)))}" for r, v in f.groupby("reason"))
            or "-",
        }
    )
st = gauges.merge(qc, on="station_no").merge(pd.DataFrame(stats), on="station_no")
st["station_name"] = st.station_name.str.slice(0, 28)
st["first"] = st["first"].astype(str).str[:10]
md(
    f"24 OPW gauges within 15 km of a Suir forecast point, 15-min (5-min in the early years), {str(qc['first'].min())[:10]} onwards."
)
md(f"**{qc.pct_provisional.mean():.1f}% of values are quality code 254 (unchecked)**: OPW has not quality-controlled")
md("these rain records, so we have to.")
md()
md(
    f"QC (`river_forecast.features.rain_qc`): drop 15-min values > {SPIKE_MM_15MIN:.0f} mm, then compare each gauge-year with"
)
md(
    f"the median of its {rain_qc.N_NEIGHBOURS} nearest gauges and flag: daily r < {rain_qc.MIN_CORR} (`low_corr`); a step change of"
)
md(
    f">= {rain_qc.STEP_FACTOR}x in the gauge/neighbour ratio lasting >= {rain_qc.STEP_MIN_YEARS} years (`step_bias`, the Rosegreen case);"
)
md(
    f"or a single year > {rain_qc.RATIO_OUTLIER}x off the gauge's own typical ratio (`ratio_outlier`). It iterates, so a bad"
)
md("gauge doesn't get its neighbours flagged. Consistently wet upland gauges are *not* flagged.")
md(f"**{len(flags)} gauge-years flagged** ({flags.reason.value_counts().to_dict()}).")
md()
table(st.drop(columns=["lat", "lon"]).sort_values("r_vs_neighbours"))
P = D.mean(axis=1)
flow = (
    q(f"""select date_trunc('day', timestamp) d, avg(value) q
             from read_parquet('{HD}/param=Q/station=16011.parquet') group by 1""")
    .set_index("d")
    .q
)
rows = []
for y in range(2011, 2026):
    p, f = P[P.index.year == y], flow[flow.index.year == y]
    if p.count() >= 330 and f.count() >= 330:
        rain = p.mean() * 365.25
        runoff = f.mean() * 86400 * 365.25 / (CLONMEL_AREA_KM2 * 1e6) * 1000
        rows.append((y, round(rain), round(runoff), round(runoff / rain, 2), round(rain - runoff)))
wb = pd.DataFrame(rows, columns=["year", "gauge_mean_rain_mm", "clonmel_runoff_mm", "runoff_coef", "loss_mm"])
md("**Water balance check (Clonmel 16011, 2,144 km²).** QC'd gauge-mean annual rainfall against runoff depth from")
md("Hydro-Data discharge:")
md()
table(wb)
md(
    f"Mean runoff coefficient **{wb.runoff_coef.mean():.2f}**, mean loss **{wb.loss_mm.mean():.0f} mm/yr**. That is in line with"
)
md("Irish actual evapotranspiration (roughly 400-450 mm), so the QC'd gauge mean is a credible catchment rainfall.")
md("Using the *median* of gauges instead gives coefficients near 1.0, because the median of intermittent hourly rain")
md("is biased low. Use means, or areal weighting, not medians.")
md()
H = q(f"""select station_no, date_trunc('hour', timestamp) t,
                 sum(case when value > {SPIKE_MM_15MIN} then null else value end) mm
          from read_parquet('{HD}/param=Precip/*.parquet') where timestamp >= '2011-01-01' group by all""").pivot(
    index="t", columns="station_no", values="mm"
)
Ph = rain_qc.catchment_mean(H, flags)
Qh = (
    q(f"""select date_trunc('hour', timestamp) t, avg(value) q
           from read_parquet('{HD}/param=Q/station=16011.parquet') where timestamp >= '2011-01-01' group by 1""")
    .set_index("t")
    .q
)
idx = Ph.index.intersection(Qh.index)
dq = Qh.loc[idx].diff()
lag_rise = max(range(0, 49), key=lambda h: Ph.loc[idx].corr(dq.shift(-h)))
r24 = Ph.loc[idx].rolling(24).sum()
lag_q = max(range(0, 121, 3), key=lambda h: r24.corr(Qh.loc[idx].shift(-h)))
md(f"**Response at Clonmel:** hourly gauge-mean rain correlates best with the *rise* in flow {lag_rise} h later, and")
md(f"24-h rainfall correlates best with flow about {lag_q} h later. Lead time from observed rain is therefore")
md("several hours to about a day. That is enough to be useful, and HARMONIE (+48 h) extends it.")
md()
md("**Assessment:**")
md("- *Strengths:* 24 gauges spread over the catchment, 15-min, real-time (same feed as the levels), 2005/2010")
md("  onwards, CC BY 4.0, already in our archive, and the water balance closes after QC.")
md("- *Weaknesses:* all unchecked (code 254). There are impossible spikes (e.g. Knockmealdown 81603 at 1,558 mm in")
md("  15 min in 2025, Garryduff 81606 at 1,850 mm). Some gauges have bad periods, and some have persistent bias:")
md("  Rosegreen 81615 reads about 2x its neighbours from 2019, now caught by the step-change check. Several gauges")
md("  fail together in 2019, which may be a network-wide problem that year. Sites are low-lying (treatment plants,")
md("  reservoirs), so the uplands (Galtees,")
md("  Knockmealdowns, Comeraghs) are under-sampled.")
md("- *Verdict:* **use the OPW gauges as the primary observed-rainfall input for the Suir**, with automated QC")
md("  (spike, neighbour-correlation and neighbour-ratio checks) built into the transform. Cross-check against")
md("  Met Éireann's documented daily climate-station data before relying on long-term totals. Use HARMONIE")
md("  point forecasts for the future window. Note the train/serve mismatch: training uses gauge rain, inference")
md("  uses forecast rain.")
md("- The Dodder has **no OPW rain gauges** within 15 km. Its only open rainfall is Met Éireann synoptic stations")
md("  (Casement, Phoenix Park, Dublin Airport).")
md()

(OUT / "report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {OUT / 'report.md'}")
