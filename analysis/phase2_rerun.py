# ---- exceedance ------------------------------------------------------------------
md("## Exceedance detection and lead time (corrected onset counting)")
md()
md(
    "An onset is the first hour above the threshold after at least 48 h below it, with the previous hour observed. A forecast"
)
md("catches it at lead h if the lead-h forecast exceeds the threshold within +-3 h of the onset (so the real advance")
md(
    "warning can be up to 3 h shorter than the nominal lead). Onsets are scored if they fall in the test period or a flood"
)
md("window. False alarms are forecast onsets in the test period with no observed exceedance within 24 h.")
md()
drow = []
for tname, thr in THRESHOLDS.items():
    for m in MODELS:
        d = M.detection_lead(y, {h: preds[(m, h)] for h in HORIZONS}, thr, within=score_mask)
        r = {"threshold": tname, "model": m, "onsets": len(d)}
        for h in HORIZONS:
            r[f"caught@{h}h"] = int((d.lead_h >= h).sum())
        r["median_lead_h"] = float(d.lead_h.median()) if len(d) else float("nan")
        for h in (12, 24):
            r[f"false_alarms@{h}h"] = M.false_alarm_episodes(y, preds[(m, h)], thr, within=test_valid)
            r[f"CSI@{h}h"] = round(
                M.contingency(y[score_mask & common[h]], preds[(m, h)][score_mask & common[h]], thr)["CSI"], 3
            )
        drow.append(r)
        if m == "persistence":
            assert (d.lead_h == 0).all(), "persistence must not catch an onset ahead of time"
det = pd.DataFrame(drow)
