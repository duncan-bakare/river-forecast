t_start = time.time()
v1 = pd.read_csv(ROOT / "docs" / "phase2" / "skill.csv")
frame = pd.read_parquet(STORE / "clonmel_hourly.parquet")
y = frame[f"lvl_{ds.TARGET}"]
X = ds.features(frame)
T = ds.targets(frame, HORIZONS)
idx = frame.index
events = ds.flood_events(y, N_EVENTS)
events["fold"] = np.arange(len(events)) % 2  # alternate by size, so both folds hold big and small floods
in_events = ds.in_windows(idx, events)
split = pd.Series(np.where(idx < TRAIN_END, "train", np.where(idx < CAL_END, "cal", "test")), idx)
event_valid = pd.Series(in_events, idx)
fold_valid = {f: pd.Series(ds.in_windows(idx, events[events.fold == f]), idx) for f in (0, 1)}
checked_valid = frame.target_checked
test_valid = split == "test"
score_mask = test_valid | event_valid

# ---- fit + predict, saving everything ---------------------------------------
preds, fitted, raw_q = {}, {}, {}
for h in HORIZONS:
    t = T[h]
    ok_label = t.checked & t.dy.notna() & ~in_events
    tr, ca = (split == "train") & ok_label, (split == "cal") & ok_label
    for m in (Persistence(), UpstreamLinear(), LGBMQuantile(HIGH_REGIME, alpha=ALPHA)):
        if isinstance(m, LGBMQuantile):
            m.fit(X[tr], t.dy[tr], X[ca], t.dy[ca])
            raw_q[h] = m.raw_interval(X)
        else:
            m.fit(X[tr], t.dy[tr])
        preds[(m.name, h)] = (y + m.predict(X)).shift(h)
        fitted[(m.name, h)] = m
    print(f"h={h} fitted; lgbm trees={fitted[('lightgbm', h)].point.best_iteration_}", flush=True)
pd.DataFrame({f"{m}_{h}": s for (m, h), s in preds.items()}).to_parquet(STORE / "phase2_rerun_preds.parquet")
with open(STORE / "phase2_rerun_models.pkl", "wb") as fh:
    pickle.dump({k: v for k, v in fitted.items() if k[0] != "persistence"}, fh)

# common rows: every model forecasts and the observation exists, so models are compared like for like
common = {h: y.notna() & pd.concat([preds[(m, h)] for m in MODELS], axis=1).notna().all(axis=1) for h in HORIZONS}


def sets(h):
    c = common[h]
    return {
        "test, checked labels (2022-2026)": test_valid & checked_valid & ~event_valid & c,
        "test, provisional labels (2026)": test_valid & ~checked_valid & c,
        "flood backtests (8 events)": event_valid & c,
    }


def bootstrap_skill(o, f, r, n=300, seed=0):
    df = pd.DataFrame({"o": o, "f": f, "r": r}).dropna()
    groups = [g for _, g in df.groupby(pd.Grouper(freq="7D")) if len(g)]
    if len(groups) < 5:
        return (float("nan"), float("nan"))
    rng = np.random.default_rng(seed)
    vals = []
    for _ in range(n):
        pick = pd.concat([groups[i] for i in rng.integers(0, len(groups), len(groups))])
        vals.append(1 - ((pick.f - pick.o) ** 2).mean() / ((pick.r - pick.o) ** 2).mean())
    return tuple(np.percentile(vals, [5, 95]))


